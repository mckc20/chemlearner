test('library chips expand, retain access and focus after viewing a compound, and collapse', async () => {
  const user = userEvent.setup()
  start(6)
  const region = () => screen.getByRole('region', { name: /In your library ·/ })
  const chips = () => within(within(region()).getByRole('list')).getAllByRole('button')
  expect(chips()).toHaveLength(4)
  const expand = within(region()).getByRole('button', { name: /Show all/ })
  expect(expand).toHaveAttribute('aria-expanded', 'false')
  await user.click(expand)
  expect(chips().length).toBeGreaterThan(4)
  const count = chips().length
  const lastChip = chips().at(-1)
  const name = lastChip.getAttribute('aria-label')
  await user.click(lastChip)
  await user.keyboard('{Escape}')
  expect(chips()).toHaveLength(count)
  expect(within(region()).getByRole('button', { name, exact: true })).toHaveFocus()
  await user.click(within(region()).getByRole('button', { name: 'Show less' }))
  expect(chips()).toHaveLength(4)
  expect(within(region()).getByRole('button', { name: /Show all/ })).toHaveAttribute('aria-expanded', 'false')
})
