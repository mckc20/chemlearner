test('every element renders all four tabs using bundled data', () => {
  const props = { onChange: vi.fn(), onNavigate: vi.fn(), onClose: vi.fn(), compounds: [], onOpenCompound: vi.fn() }
  const view = render(<LanguageProvider><ElementProfileDialog {...props} profile={initialProfile(1)} /></LanguageProvider>)
  for (let number = 1; number <= 118; number++) {
    for (const tab of ['overview', 'structure', 'properties', 'isotopes']) {
      view.rerender(<LanguageProvider><ElementProfileDialog {...props} profile={{ ...initialProfile(number), tab }} /></LanguageProvider>)
      expect(screen.getByRole('dialog')).toBeInTheDocument()
      expect(within(screen.getByRole('tabpanel')).queryByText('undefined')).not.toBeInTheDocument()
    }
  }
}, 30000)

