import { act, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import PeriodicTableQuiz from './PeriodicTableQuiz'
import { LanguageProvider } from '../i18n/LanguageContext'
import { QUIZ_SETTINGS_KEY, saveSettings } from '../data/periodicQuiz'
import { elements, mainElements, detachedElements, families, matchesElementName } from '../data/periodicElements'

beforeEach(() => {
  localStorage.setItem('chemlearner_language', 'en')
  localStorage.removeItem(QUIZ_SETTINGS_KEY)
  vi.spyOn(Math, 'random').mockReturnValue(0.999999)
})
afterEach(() => {
  localStorage.removeItem('chemlearner_language')
  localStorage.removeItem(QUIZ_SETTINGS_KEY)
  vi.restoreAllMocks()
})

function renderQuiz(initialConfig) {
  return render(<LanguageProvider><PeriodicTableQuiz onNavigate={() => {}} initialConfig={initialConfig} /></LanguageProvider>)
}

function cell(row, column) {
  return screen.getByRole('button', { name: `Answer row ${row}, column ${column}` })
}

function startFind(count = 3, wrongAnswer = 'retry') {
  return renderQuiz({ mode: 'find', count, wrongAnswer, families })
}

function changeCount(count) {
  fireEvent.change(screen.getByLabelText('Round length'), { target: { value: 'custom' } })
  fireEvent.change(screen.getByLabelText('Number of elements'), { target: { value: String(count) } })
}

test('shared element data covers the full existing layout and grades spelling variants', () => {
  expect(elements).toHaveLength(118)
  expect(new Set(elements.map(element => element.number)).size).toBe(118)
  expect(mainElements).toHaveLength(88)
  expect(detachedElements).toHaveLength(30)
  expect(new Set(families).size).toBe(10)
  expect(elements.find(element => element.symbol === 'Hf')).toMatchObject({ period: 6, group: 4 })
  expect(elements.find(element => element.symbol === 'La')).toMatchObject({ period: 8, group: 1 })
  expect(elements.find(element => element.symbol === 'Ac')).toMatchObject({ period: 9, group: 1 })
  expect(matchesElementName(' ALUMINUM ', elements[12], 'en')).toBe(true)
  expect(matchesElementName(' cÄsium ', elements[54], 'de')).toBe(true)
  expect(matchesElementName('Hydrogen', elements[0], 'de')).toBe(false)
})

test('self-test starts blank, flips cells independently, and hides all', () => {
  renderQuiz()
  fireEvent.click(screen.getByRole('button', { name: 'Start' }))
  const grid = screen.getByRole('region', { name: 'Element grid' })
  expect(within(grid).getAllByRole('button')).toHaveLength(118)
  expect(within(grid).queryByText('Hydrogen')).not.toBeInTheDocument()
  const hydrogen = within(grid).getByRole('button', { name: 'Reveal row 1, column 1' })
  const helium = within(grid).getByRole('button', { name: 'Reveal row 1, column 18' })
  expect(hydrogen).toHaveClass('periodic-quiz-cell--blank')
  fireEvent.click(hydrogen)
  expect(hydrogen).toHaveClass('periodic-quiz-cell--revealed')
  expect(within(hydrogen).getByText('Hydrogen')).toBeInTheDocument()
  fireEvent.click(helium)
  fireEvent.click(hydrogen)
  expect(hydrogen).toHaveClass('periodic-quiz-cell--blank')
  expect(helium).toHaveClass('periodic-quiz-cell--revealed')
  fireEvent.click(screen.getByRole('button', { name: 'Hide all and start over' }))
  expect(helium).toHaveClass('periodic-quiz-cell--blank')
})

test('a blank cell exposes only its position and opens from the keyboard', async () => {
  const user = userEvent.setup()
  renderQuiz()
  fireEvent.click(screen.getByRole('button', { name: 'Start' }))
  const cell = screen.getByRole('button', { name: 'Reveal row 1, column 1' })
  expect(cell).not.toHaveAttribute('title')
  expect(cell.getAttribute('aria-label')).not.toMatch(/Hydrogen|Nonmetal|\bH\b/)
  cell.focus()
  await user.keyboard('{Enter}')
  expect(cell).toHaveAttribute('aria-pressed', 'true')
  expect(within(cell).getByText('Hydrogen')).toBeInTheDocument()
})

test('find mode scores the requested element, keeps cards revealed, and colors completed results', () => {
  startFind()
  const hydrogen = cell(1, 1)
  const helium = cell(1, 18)
  const lithium = cell(2, 1)
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  expect(cell(2, 2)).toBeDisabled()
  expect(hydrogen.getAttribute('aria-label')).not.toMatch(/Hydrogen|Nonmetal/)
  expect(hydrogen.className).not.toContain('element-cell--nonmetal')
  fireEvent.click(lithium)
  expect(lithium).toHaveClass('periodic-quiz-cell--wrong')
  expect(lithium).toBeEmptyDOMElement()
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  fireEvent.click(hydrogen)
  expect(hydrogen).toBeDisabled()
  expect(hydrogen).toHaveClass('periodic-quiz-cell--revealed')
  expect(screen.getByText('Found: 1/3')).toBeInTheDocument()
  expect(screen.getByText('Points: 0/3')).toBeInTheDocument()
  fireEvent.click(helium)
  fireEvent.click(lithium)
  expect(screen.getByText('Round complete!')).toBeInTheDocument()
  expect(screen.getByText('Points: 2/3')).toBeInTheDocument()
  expect(hydrogen).toHaveClass('periodic-quiz-cell--incorrect')
  expect(hydrogen).toHaveAccessibleName(/Incorrect/)
  expect(helium).toHaveClass('periodic-quiz-cell--correct')
  expect(lithium).toHaveClass('periodic-quiz-cell--correct')
  expect(within(hydrogen).getByText('✕')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'New round' }))
  expect(screen.getByText('Points: 0/3')).toBeInTheDocument()
  expect(cell(1, 1)).toBeEnabled()
})

test('wrong cards stay red until the element is found or skipped', () => {
  vi.useFakeTimers()
  try {
    startFind(4)
    const helium = cell(1, 18)
    const lithium = cell(2, 1)
    fireEvent.click(helium)
    fireEvent.click(lithium)
    act(() => vi.advanceTimersByTime(5000))
    expect(helium).toHaveClass('periodic-quiz-cell--wrong')
    expect(lithium).toHaveClass('periodic-quiz-cell--wrong')
    fireEvent.click(cell(1, 1))
    expect(helium).not.toHaveClass('periodic-quiz-cell--wrong')
    expect(lithium).not.toHaveClass('periodic-quiz-cell--wrong')
    fireEvent.click(lithium)
    expect(lithium).toHaveClass('periodic-quiz-cell--wrong')
    fireEvent.click(screen.getByRole('button', { name: 'Skip' }))
    expect(lithium).not.toHaveClass('periodic-quiz-cell--wrong')
    fireEvent.click(lithium)
    expect(screen.getByText('Points: 1/4')).toBeInTheDocument()
  } finally {
    vi.useRealTimers()
  }
})

test('Skip postpones untouched elements without losing their point', () => {
  startFind(2)
  fireEvent.click(screen.getByRole('button', { name: 'Skip' }))
  expect(screen.getByRole('heading', { name: 'Helium' })).toBeInTheDocument()
  fireEvent.click(cell(1, 18))
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Skip' }))
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  fireEvent.click(cell(1, 1))
  expect(screen.getByText('Points: 2/2')).toBeInTheDocument()
})

test('automatic skipping preserves the mistake when the element returns', () => {
  startFind(2, 'skip')
  fireEvent.click(cell(1, 18))
  expect(screen.getByRole('heading', { name: 'Helium' })).toBeInTheDocument()
  expect(cell(1, 18)).not.toHaveClass('periodic-quiz-cell--wrong')
  fireEvent.click(cell(1, 18))
  fireEvent.click(cell(1, 1))
  expect(screen.getByText('Points: 1/2')).toBeInTheDocument()
})

test('settings confirmation supports Cancel, deferred application, and restarting', () => {
  startFind()
  fireEvent.click(cell(1, 1))
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }))
  changeCount(2)
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  expect(screen.getByRole('dialog', { name: 'Restart to apply settings?' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
  expect(screen.getByLabelText('Number of elements')).toHaveValue(2)
  expect(screen.getByText('Found: 1/3')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Apply in next round' }))
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(screen.getByText('Found: 1/3')).toBeInTheDocument()
  expect(JSON.parse(localStorage.getItem(QUIZ_SETTINGS_KEY)).count).toBe(2)
  fireEvent.click(cell(1, 18))
  fireEvent.click(cell(2, 1))
  fireEvent.click(screen.getByRole('button', { name: 'New round' }))
  expect(screen.getByText('Found: 0/2')).toBeInTheDocument()
  fireEvent.click(cell(1, 1))
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }))
  changeCount(1)
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(screen.getByText('Found: 0/1')).toBeInTheDocument()
  expect(screen.getByText('Points: 0/1')).toBeInTheDocument()
  expect(cell(1, 1)).toBeEnabled()
})

test('settings trap focus, Escape returns to editing, and cancel discards changes', async () => {
  const user = userEvent.setup()
  startFind()
  const settings = screen.getByRole('button', { name: 'Settings' })
  await user.click(settings)
  expect(screen.getByLabelText('Alkali metal')).toHaveFocus()
  await user.tab({ shift: true })
  expect(screen.getByRole('button', { name: 'Apply', exact: true })).toHaveFocus()
  await user.tab()
  expect(screen.getByLabelText('Alkali metal')).toHaveFocus()
  changeCount(1)
  await user.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  await user.keyboard('{Escape}')
  expect(screen.getByRole('dialog', { name: 'Settings' })).toBeInTheDocument()
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(settings).toHaveFocus()
  await user.click(settings)
  expect(screen.getByLabelText('Number of elements')).toHaveValue(3)
})

test('setup restores preferences, filters families, clamps count, and rejects empty families', () => {
  saveSettings({ families: ['noble'], count: 'all', wrongAnswer: 'skip' })
  renderQuiz()
  fireEvent.click(screen.getByLabelText('Find the element'))
  expect(screen.getByLabelText('Noble gas')).toBeChecked()
  expect(screen.getByLabelText('Nonmetal')).not.toBeChecked()
  expect(screen.getByLabelText('After a wrong answer')).toHaveValue('skip')
  expect(screen.getByRole('option', { name: 'All selected elements (7)' })).toBeInTheDocument()
  fireEvent.click(screen.getByLabelText('Noble gas'))
  expect(screen.getByRole('button', { name: 'Start' })).toBeDisabled()
  fireEvent.click(screen.getByLabelText('Noble gas'))
  fireEvent.click(screen.getByLabelText('Nonmetal'))
  changeCount(10)
  fireEvent.click(screen.getByLabelText('Nonmetal'))
  expect(screen.getByLabelText('Number of elements')).toHaveValue(7)
  fireEvent.change(screen.getByLabelText('Number of elements'), { target: { value: '0' } })
  expect(screen.getByRole('button', { name: 'Start' })).toBeDisabled()
  fireEvent.change(screen.getByLabelText('Number of elements'), { target: { value: '2' } })
  fireEvent.click(screen.getByRole('button', { name: 'Start' }))
  expect(screen.getByText('Found: 0/2')).toBeInTheDocument()
  expect(cell(1, 1)).toBeDisabled()
  expect(cell(1, 18)).toBeEnabled()
  expect(cell(2, 18)).toBeEnabled()
  expect(cell(3, 18)).toBeDisabled()
})

