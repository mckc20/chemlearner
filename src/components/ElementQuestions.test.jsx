import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import PeriodicTableQuiz from './PeriodicTableQuiz'
import { LanguageProvider, useLanguage } from '../i18n/LanguageContext'
import { QUIZ_SETTINGS_KEY, readSettings, saveSettings } from '../data/periodicQuiz'

beforeEach(() => {
  localStorage.setItem('chemlearner_language', 'en')
  localStorage.removeItem(QUIZ_SETTINGS_KEY)
  vi.spyOn(Math, 'random').mockReturnValue(0.999999)
})
afterEach(() => {
  localStorage.removeItem('chemlearner_language')
  localStorage.removeItem(QUIZ_SETTINGS_KEY)
  vi.restoreAllMocks()
})

function LanguageButton() {
  const { setLanguage } = useLanguage()
  return <button onClick={() => setLanguage('de')}>Deutsch</button>
}

function renderQuiz(config = { mode: 'questions', count: 2 }) {
  return render(<LanguageProvider><LanguageButton /><PeriodicTableQuiz initialConfig={config} onNavigate={() => {}} /></LanguageProvider>)
}

function fill(symbol, number, family) {
  fireEvent.change(screen.getByRole('textbox', { name: 'Symbol' }), { target: { value: symbol } })
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Atomic number' }), { target: { value: number } })
  fireEvent.change(screen.getByRole('combobox', { name: 'Family' }), { target: { value: family } })
}
const submit = () => fireEvent.click(screen.getByRole('button', { name: 'Submit answers' }))
const next = () => fireEvent.click(screen.getByRole('button', { name: 'Next', exact: true }))

test('renders only the form, grades all selected fields, and shows results without a table', () => {
  renderQuiz()
  expect(screen.queryByRole('region', { name: 'Element grid' })).not.toBeInTheDocument()
  expect(screen.queryByRole('list', { name: 'Element families' })).not.toBeInTheDocument()
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveFocus()
  expect(screen.getByRole('button', { name: 'Submit answers' })).toBeDisabled()
  fill('H', '1', 'noble')
  submit()
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveAttribute('aria-invalid', 'true')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('H')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveAttribute('readonly')
  expect(screen.getByRole('spinbutton', { name: 'Atomic number' })).toHaveAttribute('readonly')
  expect(screen.getByRole('combobox', { name: 'Family' })).toBeEnabled()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveClass('periodic-answer-input--correct')
  expect(document.querySelector('.periodic-question-flash--incorrect')).toBeInTheDocument()
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveValue('noble')
  expect(screen.getByText('Answered: 0/2')).toBeInTheDocument()
  fireEvent.change(screen.getByRole('combobox', { name: 'Family' }), { target: { value: 'nonmetal' } })
  submit()
  expect(screen.getByText('All answers are correct!')).toBeInTheDocument()
  expect(document.querySelector('.periodic-question-flash--correct')).toBeInTheDocument()
  next()
  expect(screen.getByRole('heading', { name: 'Helium' })).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveFocus()
  expect(screen.getByText('Points: 0/2')).toBeInTheDocument()
  fill('he', '2', 'noble')
  submit()
  next()
  const results = screen.getByRole('list', { name: 'Element results' })
  expect(within(results).getAllByRole('listitem')).toHaveLength(2)
  expect(within(results).getByText('Hydrogen').closest('li')).toHaveClass('periodic-question-result--incorrect')
  expect(within(results).getByText('Helium').closest('li')).toHaveClass('periodic-question-result--correct')
  expect(screen.getByText('Points: 1/2')).toBeInTheDocument()
  expect(screen.getByRole('heading', { name: 'Round complete!' })).toHaveFocus()
  expect(screen.queryByRole('region', { name: 'Element grid' })).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'New round' }))
  expect(screen.getByText('Answered: 0/2')).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('')
})

test('Skip clears inputs and preserves point eligibility, including when only one element remains', () => {
  renderQuiz({ mode: 'questions', count: 1 })
  fill('wrong', '9', 'noble')
  fireEvent.click(screen.getByRole('button', { name: 'Skip' }))
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('')
  fill('H', '1', 'nonmetal')
  submit()
  expect(screen.getByText('Points: 1/1')).toBeInTheDocument()
})

test('first-try feedback shows corrections, locks the card, and waits for Next', () => {
  renderQuiz({ mode: 'questions', count: 2, questionFeedback: 'first' })
  fill('He', '2', 'noble')
  submit()
  expect(screen.getByRole('heading', { name: 'Hydrogen' })).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('He')
  expect(screen.getByRole('spinbutton', { name: 'Atomic number' })).toHaveValue(2)
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveValue('noble')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveAccessibleDescription('Incorrect Correct answer H')
  expect(screen.getByRole('spinbutton', { name: 'Atomic number' })).toHaveAccessibleDescription('Incorrect Correct answer 1')
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveAccessibleDescription('Incorrect Correct answer Nonmetal')
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveClass('periodic-answer-input--incorrect')
  expect(screen.getByText('Points: 0/2')).toBeInTheDocument()
  expect(screen.getByRole('combobox', { name: 'Family' })).toBeDisabled()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveAttribute('readonly')
  expect(screen.queryByRole('button', { name: 'Submit answers' })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Skip' })).not.toBeInTheDocument()
  expect(screen.getByText('Answered: 1/2')).toBeInTheDocument()
  next()
  expect(screen.getByRole('heading', { name: 'Helium' })).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('')
  fill('He', '2', 'noble')
  submit()
  expect(screen.getByText('All answers are correct!')).toBeInTheDocument()
  next()
  expect(screen.getByText('Points: 1/2')).toBeInTheDocument()
  expect(screen.getByRole('list', { name: 'Element results' })).toBeInTheDocument()
})

test('setup enforces an unused clue, restores preferences, and filters eligible elements', () => {
  saveSettings({ families: ['noble'], count: 1, answerFields: ['name', 'family'] })
  renderQuiz(null)
  fireEvent.click(screen.getByLabelText('Element questions'))
  expect(screen.getByRole('checkbox', { name: 'Name' })).toBeChecked()
  expect(screen.getByText('Given: Symbol')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('checkbox', { name: 'Symbol' }))
  expect(screen.getByText('Given: Atomic number')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('checkbox', { name: 'Atomic number' }))
  expect(screen.getByRole('button', { name: 'Start' })).toBeDisabled()
  expect(screen.getByRole('alert')).toHaveTextContent('Leave name, symbol, or atomic number unselected')
  for (const field of ['Name', 'Symbol', 'Atomic number', 'Family']) fireEvent.click(screen.getByRole('checkbox', { name: field }))
  expect(screen.getByRole('button', { name: 'Start' })).toBeDisabled()
  fireEvent.click(screen.getByRole('checkbox', { name: 'Family' }))
  fireEvent.click(screen.getByRole('button', { name: 'Start' }))
  expect(screen.getByRole('heading', { name: 'Helium' })).toBeInTheDocument()
  expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
  expect(within(screen.getByRole('combobox', { name: 'Family' })).getAllByRole('option')).toHaveLength(11)
  expect(readSettings().answerFields).toEqual(['family'])
})

test('settings support cancel, deferred fields, and immediate restart without changing active questions', () => {
  renderQuiz()
  fill('H', '1', 'nonmetal')
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Symbol' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Name' }))
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
  expect(screen.getByRole('dialog', { name: 'Settings' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Apply in next round' }))
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('H')
  expect(readSettings().answerFields).toEqual(['name', 'number', 'family'])
  submit()
  next()
  fill('He', '2', 'noble')
  submit()
  next()
  fireEvent.click(screen.getByRole('button', { name: 'New round' }))
  expect(screen.getByRole('heading', { name: 'H', exact: true })).toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Name' })).toHaveValue('')
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Family' }))
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(screen.queryByRole('combobox', { name: 'Family' })).not.toBeInTheDocument()
  expect(screen.getByText('Points: 0/2')).toBeInTheDocument()
})

test('language switching preserves inputs and grades localized names via keyboard submission', async () => {
  const user = userEvent.setup()
  renderQuiz({ mode: 'questions', count: 1, answerFields: ['name'] })
  expect(screen.getByRole('heading', { name: 'H', exact: true })).toBeInTheDocument()
  await user.type(screen.getByRole('textbox', { name: 'Name' }), 'Wasserstoff')
  await user.click(screen.getByRole('button', { name: 'Deutsch' }))
  expect(screen.getByRole('textbox', { name: 'Name' })).toHaveValue('Wasserstoff')
  screen.getByRole('textbox', { name: 'Name' }).focus()
  await user.keyboard('{Enter}')
  expect(screen.getByText('Punkte: 1/1')).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Weiter', exact: true }))
  expect(screen.getByRole('list', { name: 'Ergebnisse der Elemente' })).toHaveTextContent('Wasserstoff')
})

test('correct family fields lock while incorrect text stays editable; retries replay the red flash', () => {
  renderQuiz({ mode: 'questions', count: 1 })
  fill('He', '2', 'nonmetal')
  submit()
  expect(screen.getByRole('combobox', { name: 'Family' })).toBeDisabled()
  expect(screen.getByRole('combobox', { name: 'Family' })).toHaveClass('periodic-answer-input--correct')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).not.toHaveAttribute('readonly')
  expect(screen.getByRole('spinbutton', { name: 'Atomic number' })).toHaveClass('periodic-answer-input--incorrect')
  const flash = document.querySelector('.periodic-question-flash--incorrect')
  submit()
  expect(document.querySelector('.periodic-question-flash--incorrect')).not.toBe(flash)
  expect(screen.getByText('Correct', { exact: true })).toHaveClass('sr-only')
  for (const text of screen.getAllByText('Incorrect', { exact: true })) expect(text).toHaveClass('sr-only')
  fireEvent.change(screen.getByRole('textbox', { name: 'Symbol' }), { target: { value: 'H' } })
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Atomic number' }), { target: { value: '1' } })
  submit()
  expect(screen.getByRole('button', { name: 'Next', exact: true })).toHaveFocus()
  expect(screen.getByText('Points: 0/1')).toBeInTheDocument()
})

test('question feedback preference replaces automatic skip and persists for the next round', () => {
  renderQuiz()
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }))
  const select = screen.getByRole('combobox', { name: 'Answer feedback' })
  expect(within(select).queryByRole('option', { name: 'Automatically skip' })).not.toBeInTheDocument()
  fireEvent.change(select, { target: { value: 'first' } })
  fireEvent.click(screen.getByRole('button', { name: 'Apply', exact: true }))
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(readSettings().questionFeedback).toBe('first')
  fill('He', '1', 'nonmetal')
  submit()
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveValue('He')
  expect(screen.getByRole('textbox', { name: 'Symbol' })).toHaveAccessibleDescription('Incorrect Correct answer H')
})
